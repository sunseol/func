DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'daily_reports_report_type_core_check') THEN
    ALTER TABLE public.daily_reports ADD CONSTRAINT daily_reports_report_type_core_check
      CHECK (report_type IN ('morning', 'evening', 'weekly')) NOT VALID;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'draft_reports_report_type_core_check') THEN
    ALTER TABLE public.draft_reports ADD CONSTRAINT draft_reports_report_type_core_check
      CHECK (report_type IS NULL OR report_type IN ('morning', 'evening', 'weekly')) NOT VALID;
  END IF;
END $$;
ALTER TABLE public.daily_reports VALIDATE CONSTRAINT daily_reports_report_type_core_check;
ALTER TABLE public.draft_reports VALIDATE CONSTRAINT draft_reports_report_type_core_check;

DO $$
DECLARE
  table_name TEXT;
  constraint_name TEXT;
BEGIN
  FOR table_name, constraint_name IN
    SELECT * FROM (VALUES
      ('daily_reports', 'daily_reports_user_id_core_fkey'),
      ('draft_reports', 'draft_reports_user_id_core_fkey'),
      ('notification_settings', 'notification_settings_user_id_core_fkey'),
      ('notification_history', 'notification_history_user_id_core_fkey')
    ) AS table_constraints(table_name, constraint_name)
  LOOP
    IF NOT EXISTS (
      SELECT 1
      FROM pg_constraint c
      WHERE c.conrelid = format('public.%I', table_name)::regclass
        AND c.contype = 'f'
        AND c.confrelid = 'auth.users'::regclass
    ) THEN
      EXECUTE format(
        'ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE NOT VALID',
        table_name, constraint_name
      );
    END IF;
  END LOOP;
END $$;

DO $$
DECLARE
  table_name TEXT;
  constraint_name TEXT;
BEGIN
  FOR table_name, constraint_name IN
    SELECT * FROM (VALUES
      ('daily_reports', 'daily_reports_user_id_core_fkey'),
      ('draft_reports', 'draft_reports_user_id_core_fkey'),
      ('notification_settings', 'notification_settings_user_id_core_fkey'),
      ('notification_history', 'notification_history_user_id_core_fkey')
    ) AS table_constraints(table_name, constraint_name)
  LOOP
    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = constraint_name) THEN
      EXECUTE format('ALTER TABLE public.%I VALIDATE CONSTRAINT %I', table_name, constraint_name);
    END IF;
  END LOOP;
END $$;

DO $$
DECLARE
  table_name TEXT;
  index_name TEXT;
  constraint_name TEXT;
BEGIN
  FOR table_name, index_name, constraint_name IN
    SELECT * FROM (VALUES
      ('daily_reports', 'daily_reports_id_core_unique', 'daily_reports_pkey_core'),
      ('draft_reports', 'draft_reports_id_core_unique', 'draft_reports_pkey_core'),
      ('notification_settings', 'notification_settings_id_core_unique', 'notification_settings_pkey_core'),
      ('notification_history', 'notification_history_id_core_unique', 'notification_history_pkey_core')
    ) AS table_constraints(table_name, index_name, constraint_name)
  LOOP
    EXECUTE format('CREATE UNIQUE INDEX IF NOT EXISTS %I ON public.%I(id)', index_name, table_name);
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint
      WHERE conrelid = format('public.%I', table_name)::regclass AND contype = 'p'
    ) THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I PRIMARY KEY USING INDEX %I', table_name, constraint_name, index_name);
    END IF;
  END LOOP;
END $$;

